#!/usr/bin/env python3
"""
build_dest.py — materialise a destination-specific Pebble project tree from
the canonical `src/` + a destination JSON in `destinations/<name>.json`.

Why this exists:
  The watch-side code is generic — the only things that change between
  destinations (WDW, Disneyland, Universal, …) are:
    * the list of parks (UUIDs + display names)
    * the app UUID (so watches treat them as different apps)
    * the displayed app name
  Rather than keep N hand-synced copies in `dist/`, we generate them from
  a single JSON manifest + the src/ tree. Output goes to `dist/<name>/`.

Usage:
    python3 scripts/build_dest.py wdw           # generate dist/wdw/
    python3 scripts/build_dest.py wdw --build   # … and run pebble build
    python3 scripts/build_dest.py wdw --install emery   # build + install

Destination JSON format (see destinations/wdw.json):
    {
      "destinationId": "<themeparks.wiki dest uuid>",
      "appUuid": "<pebble app uuid, stable per destination>",
      "name": "Walt Disney World",
      "shortName": "WDW",
      "parks": [{"id": "<park uuid>", "name": "Magic Kingdom"}, …]
    }
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any, Optional

REPO_ROOT = Path(__file__).resolve().parent.parent
DESTINATIONS_DIR = REPO_ROOT / "destinations"
SRC_DIR = REPO_ROOT / "src"
DIST_DIR = REPO_ROOT / "dist"
# `pebble build` drops its output inside the destination's build tree;
# after a successful build we copy the .pbw here so the shippable
# artifacts for every destination live together and are easy to find.
BUILDS_DIR = REPO_ROOT / "builds"


# ── Generators ────────────────────────────────────────────────────────────

def gen_config_h(dest: dict[str, Any]) -> str:
    name = dest["name"].replace('"', '\\"')
    if dest.get("multiDestination", False):
        return f"""\
/*
 * config.h — generated by scripts/build_dest.py from destinations/{dest['_file']}.
 * Edit the JSON, not this file.
 */
#pragma once

#include <stdint.h>

#define MULTI_DESTINATION 1

typedef struct {{
    const char *id;
    const char *name;
    /* Icon token — drawn by park_picker.c. Known values (case-sensitive):
     *   "castle", "sphere", "star", "tree". Anything unrecognised falls
     *   back to a plain coloured circle. */
    const char *icon;
    /* Colour token — maps to a Pebble GColor at runtime:
     *   "pink", "cyan", "red", "green", "orange", "yellow", "purple".
     *   Unknowns render as dark grey. */
    const char *color;
#ifdef MULTI_DESTINATION
    char id_buf[40];
    char name_buf[40];
    char icon_buf[16];
    char color_buf[16];
#endif
}} park_config_t;

#define APP_NAME "{name}"
#define MAX_PARKS 10

extern park_config_t g_parks[MAX_PARKS];
extern uint8_t num_parks;

/* Compatibility shim: existing code uses NUM_PARKS; in multi-destination
 * mode this resolves to the runtime variable num_parks instead. */
#define NUM_PARKS num_parks

/* Auto-refresh interval (Pebble timer expects ms). */
#define REFRESH_INTERVAL_MS (5 * 60 * 1000)
"""
    n = len(dest["parks"])
    return f"""\
/*
 * config.h — generated by scripts/build_dest.py from destinations/{dest['_file']}.
 * Edit the JSON, not this file.
 */
#pragma once

#include <stdint.h>

typedef struct {{
    const char *id;
    const char *name;
    /* Icon token — drawn by park_picker.c. Known values (case-sensitive):
     *   "castle", "sphere", "star", "tree". Anything unrecognised falls
     *   back to a plain coloured circle. */
    const char *icon;
    /* Colour token — maps to a Pebble GColor at runtime:
     *   "pink", "cyan", "red", "green", "orange", "yellow", "purple".
     *   Unknowns render as dark grey. */
    const char *color;
#ifdef MULTI_DESTINATION
    char id_buf[40];
    char name_buf[40];
    char icon_buf[16];
    char color_buf[16];
#endif
}} park_config_t;

#define APP_NAME "{name}"
#define NUM_PARKS {n}

extern const park_config_t g_parks[NUM_PARKS];

/* Auto-refresh interval (Pebble timer expects ms). */
#define REFRESH_INTERVAL_MS (5 * 60 * 1000)
"""


def gen_config_c(dest: dict[str, Any]) -> str:
    if dest.get("multiDestination", False):
        return "\n".join([
            "/*",
            f" * config.c — generated by scripts/build_dest.py from destinations/{dest['_file']}.",
            " * Edit the JSON, not this file.",
            " */",
            "",
            '#include "config.h"',
            "",
            "park_config_t g_parks[MAX_PARKS];",
            "uint8_t num_parks = 0;",
            "",
        ])
    lines = [
        "/*",
        f" * config.c — generated by scripts/build_dest.py from destinations/{dest['_file']}.",
        " * Edit the JSON, not this file.",
        " */",
        "",
        '#include "config.h"',
        "",
        "const park_config_t g_parks[NUM_PARKS] = {",
    ]
    for p in dest["parks"]:
        pid = p["id"].replace('"', '\\"')
        pname = p["name"].replace('"', '\\"')
        icon = p.get("icon", "circle").replace('"', '\\"')
        color = p.get("color", "gray").replace('"', '\\"')
        lines.append(
            f'    {{ "{pid}", "{pname}", "{icon}", "{color}" }},'
        )
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def patched_pkjs(pkjs_src: str, dest: dict[str, Any]) -> str:
    """Rewrite DESTINATION_ID and ALL_PARK_IDS in the PKJS source with the
    destination's values. We locate the existing declarations and replace
    them — no template markers needed because the names are stable."""
    import re

    # Regex accepts either `const` or `var` — the PKJS source uses `var`
    # so the uber app can reassign at runtime, but we tolerate `const`
    # too so downstream edits don't silently break patching.
    dest_id_pat = r'(?:const|var) DESTINATION_ID = "[^"]*";'
    park_ids_pat = r"(?:const|var) ALL_PARK_IDS = \[[^\]]*\];"

    if dest.get("multiDestination", False):
        # Multi-destination: null ID, empty park list. PKJS will populate
        # these at runtime once the user selects a destination.
        out = re.sub(
            dest_id_pat,
            'var DESTINATION_ID = null;',
            pkjs_src,
            count=1,
        )
        prev = out
        out = re.sub(
            park_ids_pat,
            "var ALL_PARK_IDS = [];",
            out,
            count=1,
            flags=re.DOTALL,
        )
        if out == prev:
            raise RuntimeError(
                "Couldn't find ALL_PARK_IDS in src/pkjs/index.js — was it renamed?"
            )
        return out

    # Patch DESTINATION_ID
    dest_id = dest["destinationId"]
    out = re.sub(
        dest_id_pat,
        f'var DESTINATION_ID = "{dest_id}";',
        pkjs_src,
        count=1,
    )

    # Patch ALL_PARK_IDS
    park_lines = [
        f'  "{p["id"]}",  // {p["name"]}'
        for p in dest["parks"]
    ]
    replacement = "var ALL_PARK_IDS = [\n" + "\n".join(park_lines) + "\n];"
    prev = out
    out = re.sub(
        park_ids_pat,
        replacement,
        out,
        count=1,
        flags=re.DOTALL,
    )
    if out == prev:
        raise RuntimeError(
            "Couldn't find ALL_PARK_IDS in src/pkjs/index.js — was it renamed?"
        )
    return out


def gen_package_json(src_pkg: dict, dest: dict[str, Any]) -> dict:
    out = dict(src_pkg)
    pebble = dict(out.get("pebble", {}))
    pebble["uuid"] = dest["appUuid"]
    # `appName` is optional — the short string that appears in the
    # Pebble launcher. Falls back to the full `name` when absent.
    pebble["displayName"] = dest.get("appName") or dest["name"]
    out["pebble"] = pebble
    out["name"] = "pebble-" + dest.get("shortName", dest["name"]).lower()
    return out


# ── Filesystem ───────────────────────────────────────────────────────────

def copy_src_tree(dest_dir: Path) -> None:
    """Copy the src/ tree into dest_dir/src/, skipping generated files
    (config.c, config.h, pkjs/index.js — those come from the generators).
    Also copy wscript at the top level."""
    target_src = dest_dir / "src"
    if target_src.exists():
        shutil.rmtree(target_src)
    shutil.copytree(
        SRC_DIR,
        target_src,
        ignore=shutil.ignore_patterns(
            # generated below
            "config.c", "config.h", "index.js",
        ),
    )

    # wscript at dest root
    shutil.copy2(REPO_ROOT / "wscript", dest_dir / "wscript")


def write_generated(dest_dir: Path, dest: dict[str, Any]) -> None:
    (dest_dir / "src" / "c" / "config.h").write_text(gen_config_h(dest))
    (dest_dir / "src" / "c" / "config.c").write_text(gen_config_c(dest))

    pkjs_src = (SRC_DIR / "pkjs" / "index.js").read_text()
    (dest_dir / "src" / "pkjs" / "index.js").write_text(
        patched_pkjs(pkjs_src, dest)
    )


def write_package_json(dest_dir: Path, dest: dict[str, Any]) -> None:
    src_pkg = json.loads((REPO_ROOT / "package.json").read_text())
    out = gen_package_json(src_pkg, dest)
    (dest_dir / "package.json").write_text(json.dumps(out, indent=2) + "\n")


# ── Orchestration ────────────────────────────────────────────────────────

def build_dest(name: str) -> Path:
    dest_json = DESTINATIONS_DIR / f"{name}.json"
    if not dest_json.exists():
        raise SystemExit(f"destination not found: {dest_json}")
    dest = json.loads(dest_json.read_text())
    dest["_file"] = dest_json.name

    for required in ("appUuid", "name", "parks"):
        if required not in dest:
            raise SystemExit(f"{dest_json}: missing required field '{required}'")

    dest_dir = DIST_DIR / name
    dest_dir.mkdir(parents=True, exist_ok=True)

    copy_src_tree(dest_dir)
    write_generated(dest_dir, dest)
    write_package_json(dest_dir, dest)

    print(f"generated {dest_dir.relative_to(REPO_ROOT)}"
          f" — {len(dest['parks'])} park(s), uuid {dest['appUuid']}")
    return dest_dir


def pebble(cmd: list[str], cwd: Path) -> int:
    print(f"  $ {' '.join(cmd)}")
    return subprocess.call(cmd, cwd=cwd)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("destination",
                   help="destination name — matches destinations/<name>.json")
    p.add_argument("--build", action="store_true",
                   help="run `pebble build` after generating")
    p.add_argument("--install",
                   help="run build, then install on the given platform "
                        "(emery / gabbro / basalt / …)")
    args = p.parse_args()

    dest_dir = build_dest(args.destination)

    pbw_out: Optional[Path] = None
    if args.install or args.build:
        if pebble(["pebble", "build"], dest_dir) != 0:
            return 1
        # Copy the built .pbw into builds/<slug>.pbw so every
        # destination's latest artifact is findable in one directory.
        pbw_src = dest_dir / "build" / f"{args.destination}.pbw"
        if not pbw_src.exists():
            candidates = list((dest_dir / "build").glob("*.pbw"))
            if not candidates:
                print("no .pbw produced by pebble build")
                return 1
            pbw_src = candidates[0]
        BUILDS_DIR.mkdir(parents=True, exist_ok=True)
        pbw_out = BUILDS_DIR / f"{args.destination}.pbw"
        shutil.copy2(pbw_src, pbw_out)
        print(f"copied {pbw_src.relative_to(REPO_ROOT)} "
              f"-> {pbw_out.relative_to(REPO_ROOT)}")

    if args.install:
        install_src = pbw_out or (dest_dir / "build" / f"{args.destination}.pbw")
        if pebble(["pebble", "install", "--emulator", args.install,
                   str(install_src)], dest_dir) != 0:
            return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
